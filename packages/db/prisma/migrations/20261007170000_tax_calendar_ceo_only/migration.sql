-- Налоговый календарь IT-Park — только у CEO: убираем пункты календаря,
-- которые сотрудники (не CEO) добавили себе сами. Свои регулярные дела сотрудников не трогаем.
UPDATE "recurring_todos" r
SET "deleted_at" = NOW(), "is_active" = false
FROM "users" u
JOIN "roles" ro ON ro."id" = u."role_id"
WHERE r."owner_id" = u."id"
  AND ro."code" <> 'CEO'
  AND r."deleted_at" IS NULL
  AND r."title" IN (
    'Налог с оборота за {прошлый_месяц}',
    'Налог на доходы работников (НДФЛ) за {прошлый_месяц}',
    'Отчёт IT-Park об обороте за {прошлый_месяц}',
    'ИНПС — посчитать за {прошлый_месяц}',
    'Квартальный отчёт IT-Park за {прошлый_квартал}',
    'Статотчёт за {прошлый_квартал}',
    'Баланс (форма №1) и отчёт о финансовых результатах (форма №2) за {год}',
    'Годовой статотчёт за {прошлый_год}'
  );
