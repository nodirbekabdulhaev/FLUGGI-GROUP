import { z } from 'zod';

// ─────────────────────────── Реквизиты клиента ───────────────────────────

const text = (max: number) => z.string().trim().max(max).default('');

/** Реквизиты клиента для договора. ИНН — 9 цифр (юрлицо) или ПИНФЛ — 14 цифр (физлицо). */
export const clientRequisitesSchema = z.object({
  legalName: text(300),
  inn: z
    .string()
    .trim()
    .regex(/^(\d{9}|\d{14})?$/, 'ИНН — 9 цифр, ПИНФЛ — 14 цифр')
    .default(''),
  director: text(120),
  directorPosition: text(120),
  /** «в лице …» — родительный падеж: «директора Иванова Ивана Ивановича» */
  signerGenitive: text(200),
  basis: text(200),
  address: text(300),
  phone: text(60),
  bank: text(200),
  mfo: z
    .string()
    .trim()
    .regex(/^(\d{5})?$/, 'МФО — 5 цифр')
    .default(''),
  account: z
    .string()
    .trim()
    .regex(/^(\d{20})?$/, 'Расчётный счёт — 20 цифр')
    .default(''),
  oked: text(10),
  vatCode: text(20),
});
export type ClientRequisites = z.output<typeof clientRequisitesSchema>;
export type ClientRequisitesInput = z.input<typeof clientRequisitesSchema>;

